import Foundation
import Darwin

enum UserFiles {
    static let directory = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/RNDIS Tether", isDirectory: true)
    static let settings = directory.appendingPathComponent("settings.json")
    static let clashScript = directory.appendingPathComponent("Clash-USB.js")
    static let journal = directory.appendingPathComponent("clash-session.json")

    static func save(_ data: Data, to url: URL) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
                                               attributes: [.posixPermissions: 0o700])
        try data.write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}

struct DemandPreferences: Codable, Equatable {
    var targets: [String] = []
    var dnsServer = ""

    func validated() throws -> DemandPreferences {
        var result = self
        result.targets = []
        for raw in targets {
            let text = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            if text.isEmpty { continue }
            let target = try RoutingTarget(text).normalized
            if !result.targets.contains(target) { result.targets.append(target) }
        }
        guard result.targets.count <= 8 else { throw TetherError("最多支持 8 个目标。") }
        result.dnsServer = dnsServer.trimmingCharacters(in: .whitespacesAndNewlines)
        if !result.dnsServer.isEmpty {
            var address = in_addr()
            guard inet_pton(AF_INET, result.dnsServer, &address) == 1 || ipv6(result.dnsServer) != nil else {
                throw TetherError("Clash DNS 必须是 IPv4 或 IPv6 地址。")
            }
        }
        return result
    }

    static func load() -> DemandPreferences {
        if let data = try? Data(contentsOf: UserFiles.settings),
           let value = try? JSONDecoder().decode(DemandPreferences.self, from: data) { return value }
        return DemandPreferences()
    }

    func save() throws {
        let value = try validated()
        // Export first, so invalid Clash input never reports successful configuration.
        let existingURL = FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Library/Application Support/io.github.clash-verge-rev.clash-verge-rev/profiles/Script.js")
        let existing = (try? String(contentsOf: existingURL, encoding: .utf8)) ?? ""
        try UserFiles.save(Data(try value.clashScript(existingScript: existing).utf8), to: UserFiles.clashScript)
        try UserFiles.save(JSONEncoder().encode(value), to: UserFiles.settings)
    }

    func clashScript(existingScript: String = "") throws -> String {
        let value = try validated()
        let begin = "// BEGIN RNDIS TETHER MANAGED CONFIG"
        let end = "// END RNDIS TETHER MANAGED CONFIG"
        var original = existingScript
        if let first = original.range(of: begin) {
            guard let last = original.range(of: end, range: first.upperBound..<original.endIndex) else {
                throw TetherError("现有 Clash 脚本的 RNDIS 标记不完整，请先检查该脚本。")
            }
            original.removeSubrange(first.lowerBound..<last.upperBound)
        }
        if original.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            original = "function main(config) { return config; }\n"
        }
        let targets = try value.targets.map(RoutingTarget.init)
        let data = try JSONSerialization.data(withJSONObject: [
            "rules": targets.map { $0.clashRule(group: "RNDIS Tether") },
            "domains": targets.compactMap { $0.domain }, "dnsServer": value.dnsServer
        ], options: [.sortedKeys])
        let settings = String(decoding: data, as: UTF8.self)
        return original + "\n" + begin + "\n" + """
        // Generated by RNDIS Tether. Enable this as a Clash Verge merge script.
        // The GUI switches this selector on connect/stop. Default is DIRECT.
        function __rndisTetherApply(config) {
          const settings = \(settings);
          const group = "RNDIS Tether";
          const outbound = "RNDIS Tether USB";
          if ((config.proxies || []).some(p => p.name === outbound) ||
              (config["proxy-groups"] || []).some(p => p.name === group)) {
            throw new Error("RNDIS Tether names already exist. Enable this script only once.");
          }
          const dns = config.dns || {};
          if (dns["enhanced-mode"] === "fake-ip" &&
              dns["fake-ip-filter-mode"] && dns["fake-ip-filter-mode"] !== "blacklist") {
            throw new Error("RNDIS Tether requires fake-IP blacklist mode or redir-host DNS.");
          }
          config.ipv6 = true;
          config.proxies = [...(config.proxies || []), {
            name: outbound, type: "direct", "interface-name": "feth50", "ip-version": "dual"
          }];
          config["proxy-groups"] = [...(config["proxy-groups"] || []), {
            name: group, type: "select", proxies: ["DIRECT", outbound]
          }];
          const domains = [...new Set(settings.domains)];
          config.rules = [...settings.rules, ...(config.rules || [])];
          config.dns = { ...dns, enable: true, ipv6: true,
            "fake-ip-filter": [...new Set([...(dns["fake-ip-filter"] || []), ...domains.map(d => "+." + d)])]
          };
          if (settings.dnsServer) {
            const policy = { ...(dns["nameserver-policy"] || {}) };
            domains.forEach(d => { policy["+." + d] = [settings.dnsServer]; });
            config.dns["nameserver-policy"] = policy;
          }
          return config;
        }
        const __rndisTetherOriginalMain = main;
        main = function(config, profileName) {
          return __rndisTetherApply(__rndisTetherOriginalMain(config, profileName));
        };
        """ + "\n" + end + "\n"
    }
}
